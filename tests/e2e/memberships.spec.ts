import { expect, test, type Page } from '@playwright/test'

async function setup(page: Page, secondCategory = false) {
  await page.goto('/#/equipos')
  await page.getByLabel('Nombre del club', { exact: true }).fill('Club de prueba')
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  await page.getByRole('navigation').getByRole('link', { name: 'Temporadas', exact: true }).click()
  await page.getByRole('button', { name: 'Nueva temporada', exact: true }).click()
  const seasonForm = page.getByRole('form', { name: 'Nueva temporada', exact: true })
  await seasonForm.getByLabel('Nombre de la temporada').fill('2026')
  await seasonForm.getByLabel('Fecha de inicio').fill('2026-01-01')
  await seasonForm.getByLabel('Fecha de término').fill('2026-12-31')
  await seasonForm.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.getByRole('rowheader', { name: '2026', exact: true })).toBeVisible()
  for (const category of secondCategory ? ['sub14', 'sub16'] : ['sub14']) {
    await page.getByRole('navigation').getByRole('link', { name: 'Equipos', exact: true }).click()
    await page.getByRole('button', { name: 'Nuevo equipo', exact: true }).click()
    const form = page.getByRole('form', { name: 'Nuevo equipo', exact: true })
    const name = category === 'sub14' ? 'Iruka Sub 14' : 'Iruka Sub 16'
    await form.getByLabel('Nombre del equipo').fill(name)
    await form.getByLabel('Categoría', { exact: true }).selectOption(category)
    await form.getByRole('checkbox', { name: '2026', exact: true }).check()
    await form.getByRole('button', { name: 'Guardar', exact: true }).click()
    await expect(page.getByRole('rowheader', { name, exact: true })).toBeVisible()
  }
  await addAthlete(page, 'Álex Marín')
}
async function addAthlete(page: Page, name: string) {
  await page.getByRole('navigation').getByRole('link', { name: 'Deportistas', exact: true }).click()
  await page.getByRole('button', { name: 'Nuevo deportista', exact: true }).click()
  await page.getByLabel('Nombre del deportista', { exact: true }).fill(name)
  await page.getByLabel('Fecha de nacimiento (opcional)', { exact: true }).fill('2013-02-10')
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.getByRole('table', { name: 'Deportistas del club' }).getByRole('link', { name, exact: true })).toBeVisible()
}
async function openRoster(page: Page, team = 'Iruka Sub 14') {
  await page.getByRole('navigation').getByRole('link', { name: 'Plantillas', exact: true }).click()
  await page.getByRole('link').filter({ has: page.getByRole('heading', { level: 2, name: team, exact: true }) }).click()
  await expect(page.getByRole('heading', { level: 1, name: team, exact: true })).toBeVisible()
}
async function register(page: Page, person: string, number: string) {
  await page.getByRole('button', { name: 'Inscribir deportista', exact: true }).click()
  const form = page.getByRole('form', { name: 'Inscribir deportista', exact: true })
  await form.getByRole('button', { name: new RegExp(person) }).click()
  await form.getByLabel('Dorsal', { exact: true }).fill(number)
  await form.getByLabel('Rol habitual', { exact: true }).selectOption('punta')
  await form.getByRole('button', { name: 'Guardar', exact: true }).click({ clickCount: 2 })
}
async function offlineReady(page: Page) {
  await page.evaluate(async () => {
    await navigator.serviceWorker.ready
    if (!navigator.serviceWorker.controller) await new Promise<void>((resolve) => navigator.serviceWorker.addEventListener('controllerchange', () => resolve(), { once: true }))
  })
}

test('aceptación Hito 1 offline: un perfil en Sub 14 y Sub 16 con dorsales 5 y 8', async ({ page, context }) => {
  test.setTimeout(60_000)
  const external: string[] = []
  const errors: string[] = []
  context.on('request', (request) => { if (/^https?:/.test(request.url()) && new URL(request.url()).hostname !== '127.0.0.1') external.push(request.url()) })
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width: 1024, height: 768 })
  await setup(page, true)
  await page.getByRole('link', { name: 'Álex Marín', exact: true }).click()
  const profileUrl = page.url()
  await offlineReady(page)
  await context.setOffline(true)
  await openRoster(page)
  const firstRosterUrl = page.url()
  await register(page, 'Álex Marín', '5')
  await expect(page.getByRole('table', { name: 'Inscripciones de la plantilla' }).getByRole('row')).toHaveCount(2)
  await openRoster(page, 'Iruka Sub 16')
  await register(page, 'Álex Marín', '8')
  await page.getByRole('table', { name: 'Inscripciones de la plantilla' }).getByRole('link', { name: 'Álex Marín', exact: true }).click()
  await expect(page).toHaveURL(profileUrl)
  const inscriptions = page.getByRole('table', { name: 'Equipos y dorsales del deportista' })
  await expect(inscriptions.getByRole('row')).toHaveCount(3)
  await expect(inscriptions.getByRole('row').filter({ has: page.getByRole('link', { name: 'Iruka Sub 14', exact: true }) })).toContainText('#5')
  await expect(inscriptions.getByRole('row').filter({ has: page.getByRole('link', { name: 'Iruka Sub 16', exact: true }) })).toContainText('#8')
  await page.screenshot({ path: 'test-results/inscripciones-perfil-offline.png', fullPage: true })
  await page.getByRole('navigation').getByRole('link', { name: 'Deportistas', exact: true }).click()
  await expect(page.getByRole('table', { name: 'Deportistas del club' }).getByRole('row')).toHaveCount(2)
  await page.goto(firstRosterUrl)
  await page.getByRole('button', { name: 'Editar inscripción de Álex Marín', exact: true }).click()
  let form = page.getByRole('form', { name: 'Editar inscripción', exact: true })
  await form.getByLabel('Dorsal', { exact: true }).fill('6')
  await form.getByLabel('Rol habitual', { exact: true }).selectOption('central')
  await form.getByRole('button', { name: 'Guardar', exact: true }).click()
  await page.getByRole('button', { name: 'Archivar inscripción de Álex Marín', exact: true }).click()
  await page.getByRole('button', { name: 'Inscribir deportista', exact: true }).click()
  form = page.getByRole('form', { name: 'Inscribir deportista', exact: true })
  await expect(form.getByRole('button', { name: /Álex Marín/ })).toHaveCount(0)
  await form.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Ver solo inscripciones archivadas' }).check()
  await page.getByRole('button', { name: 'Restaurar inscripción de Álex Marín', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Ver solo inscripciones archivadas' }).uncheck()
  await expect(page.getByRole('table', { name: 'Inscripciones de la plantilla' })).toContainText('#6')
  await page.reload()
  await expect(page.getByRole('table', { name: 'Inscripciones de la plantilla' })).toContainText('Central')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/plantel-offline.png', fullPage: true })
  const reopened = await context.newPage()
  reopened.on('pageerror', (error) => errors.push(error.message))
  await reopened.goto(profileUrl)
  const restoredInscriptions = reopened.getByRole('table', { name: 'Equipos y dorsales del deportista' })
  await expect(restoredInscriptions.getByRole('row')).toHaveCount(3)
  await expect(restoredInscriptions.getByRole('row').filter({ has: reopened.getByRole('link', { name: 'Iruka Sub 14', exact: true }) })).toContainText('#6')
  await expect(restoredInscriptions.getByRole('row').filter({ has: reopened.getByRole('link', { name: 'Iruka Sub 16', exact: true }) })).toContainText('#8')
  await reopened.goto('/#/plantillas/no-existe')
  await expect(reopened.getByRole('heading', { name: 'Plantilla no encontrada', exact: true })).toBeVisible()
  expect(external).toEqual([])
  expect(errors).toEqual([])
})

test('bloquea dorsales ocupados y permite resolver la restauración de una inscripción archivada', async ({ page }) => {
  test.setTimeout(60_000)
  await setup(page)
  await addAthlete(page, 'Sol Vega')
  await openRoster(page)
  await register(page, 'Álex Marín', '5')
  await register(page, 'Sol Vega', '5')
  let form = page.getByRole('form', { name: 'Inscribir deportista', exact: true })
  await expect(form.getByRole('alert')).toContainText('dorsal')
  await expect(form.getByRole('button', { name: /Sol Vega/ })).toHaveAttribute('aria-pressed', 'true')
  await page.setViewportSize({ width: 375, height: 812 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const candidate = await form.getByRole('button', { name: /Sol Vega/ }).boundingBox()
  expect(candidate?.height).toBeGreaterThanOrEqual(44)
  await page.screenshot({ path: 'test-results/inscripcion-movil.png', fullPage: true })
  await form.getByLabel('Dorsal', { exact: true }).fill('8')
  await form.getByRole('button', { name: 'Guardar', exact: true }).click()
  await page.getByRole('button', { name: 'Archivar inscripción de Álex Marín', exact: true }).click()
  await page.getByRole('button', { name: 'Editar inscripción de Sol Vega', exact: true }).click()
  form = page.getByRole('form', { name: 'Editar inscripción', exact: true })
  await form.getByLabel('Dorsal', { exact: true }).fill('5')
  await form.getByRole('button', { name: 'Guardar', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Ver solo inscripciones archivadas' }).check()
  await page.getByRole('button', { name: 'Restaurar inscripción de Álex Marín', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('dorsal')
  await page.getByRole('button', { name: 'Editar inscripción de Álex Marín', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
  form = page.getByRole('form', { name: 'Editar inscripción', exact: true })
  await form.getByLabel('Dorsal', { exact: true }).fill('9')
  await form.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByRole('button', { name: 'Restaurar inscripción de Álex Marín', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Ver solo inscripciones archivadas' }).uncheck()
  await expect(page.getByRole('table', { name: 'Inscripciones de la plantilla' }).getByRole('row')).toHaveCount(3)
  await expect(page.getByRole('table', { name: 'Inscripciones de la plantilla' })).toContainText('#9')
})

test('protege las inscripciones entre pestañas y conserva las referencias al archivar perfiles o temporadas', async ({ page, context }) => {
  test.setTimeout(60_000)
  await setup(page)
  await addAthlete(page, 'Sol Vega')
  await openRoster(page)
  await register(page, 'Álex Marín', '5')
  const rosterUrl = page.url()
  const second = await context.newPage()
  await second.goto(rosterUrl)
  await second.getByRole('button', { name: 'Editar inscripción de Álex Marín', exact: true }).click()
  await page.getByRole('button', { name: 'Editar inscripción de Álex Marín', exact: true }).click()
  await page.getByLabel('Dorsal', { exact: true }).fill('6')
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.getByRole('table', { name: 'Inscripciones de la plantilla' })).toContainText('#6')
  await second.getByLabel('Dorsal', { exact: true }).fill('7')
  await second.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(second.getByRole('alert')).toContainText('otra edición')
  await expect(second.getByLabel('Dorsal', { exact: true })).toHaveValue('7')
  await second.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await expect(second.getByRole('table', { name: 'Inscripciones de la plantilla' })).toContainText('#6')
  await page.getByRole('table', { name: 'Inscripciones de la plantilla' }).getByRole('link', { name: 'Álex Marín', exact: true }).click()
  await page.getByRole('button', { name: 'Archivar deportista', exact: true }).click()
  await page.goto(rosterUrl)
  await expect(page.getByRole('button', { name: 'Editar inscripción de Álex Marín', exact: true })).toBeDisabled()
  await register(page, 'Sol Vega', '6')
  await expect(page.getByRole('form', { name: 'Inscribir deportista' }).getByRole('alert')).toContainText('dorsal')
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await page.getByRole('button', { name: 'Archivar inscripción de Álex Marín', exact: true }).click()
  await register(page, 'Sol Vega', '6')
  await expect(page.getByRole('table', { name: 'Inscripciones de la plantilla' })).toContainText('Sol Vega')
  await page.getByRole('navigation').getByRole('link', { name: 'Temporadas', exact: true }).click()
  await page.getByRole('button', { name: 'Archivar temporada 2026', exact: true }).click()
  await page.getByRole('navigation').getByRole('link', { name: 'Plantillas', exact: true }).click()
  await expect(page.getByRole('link').filter({ has: page.getByRole('heading', { name: 'Iruka Sub 14', exact: true }) })).toHaveCount(0)
  await page.getByRole('checkbox', { name: 'Incluir plantillas archivadas o desvinculadas' }).check()
  await page.getByRole('link').filter({ has: page.getByRole('heading', { name: 'Iruka Sub 14', exact: true }) }).click()
  await expect(page.getByRole('button', { name: 'Inscribir deportista', exact: true })).toBeDisabled()
  await expect(page.getByRole('table', { name: 'Inscripciones de la plantilla' })).toContainText('Sol Vega')
  await page.getByRole('navigation').getByRole('link', { name: 'Temporadas', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Ver solo temporadas archivadas' }).check()
  await page.getByRole('button', { name: 'Restaurar temporada 2026', exact: true }).click()
  await page.goto(rosterUrl)
  await expect(page.getByRole('button', { name: 'Inscribir deportista', exact: true })).toBeEnabled()
  await expect(page.getByRole('table', { name: 'Inscripciones de la plantilla' })).toContainText('Sol Vega')
})
