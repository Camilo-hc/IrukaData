import { expect, test, type Page } from '@playwright/test'

async function season(page: Page, name: string) {
  await page.getByRole('navigation').getByRole('link', { name: 'Temporadas', exact: true }).click()
  await page.getByRole('button', { name: 'Nueva temporada', exact: true }).click()
  const form = page.getByRole('form', { name: 'Nueva temporada', exact: true })
  await form.getByLabel('Nombre de la temporada').fill(name)
  await form.getByLabel('Fecha de inicio').fill(`${name}-01-01`)
  await form.getByLabel('Fecha de término').fill(`${name}-12-31`)
  await form.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.getByRole('rowheader', { name, exact: true })).toBeVisible()
}
async function team(page: Page, name: string, category: string, seasonName: string) {
  await page.getByRole('navigation').getByRole('link', { name: 'Equipos', exact: true }).click()
  await page.getByRole('button', { name: 'Nuevo equipo', exact: true }).click()
  const form = page.getByRole('form', { name: 'Nuevo equipo', exact: true })
  await form.getByLabel('Nombre del equipo').fill(name)
  await form.getByLabel('Categoría', { exact: true }).selectOption(category)
  await form.getByRole('checkbox', { name: seasonName, exact: true }).check()
  await form.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.getByRole('rowheader', { name, exact: true })).toBeVisible()
}
async function configured(page: Page) {
  await page.goto('/#/equipos')
  await page.getByLabel('Nombre del club', { exact: true }).fill('Club Iruka de prueba')
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Nuevo equipo', exact: true })).toBeVisible()
  await season(page, '2026')
  await season(page, '2027')
  await team(page, 'Iruka Sub 16', 'sub16', '2026')
  await team(page, 'Iruka Sub 14', 'sub14', '2026')
  await team(page, 'Equipo otra temporada', 'tc', '2027')
  await page.getByRole('navigation').getByRole('link', { name: 'Torneos', exact: true }).click()
}
async function createTournament(page: Page, name: string) {
  await page.getByRole('button', { name: 'Nuevo torneo', exact: true }).click()
  const form = page.getByRole('form', { name: 'Nuevo torneo', exact: true })
  await form.getByLabel('Nombre del torneo', { exact: true }).fill(name)
  await form.getByLabel('Temporada del torneo', { exact: true }).selectOption({ label: '2026' })
  await form.getByRole('checkbox', { name: 'Iruka Sub 16 · Femenino · Sub 16', exact: true }).check()
  await form.getByRole('button', { name: 'Guardar torneo', exact: true }).click()
  await expect(page.getByRole('rowheader', { name: new RegExp(name) })).toBeVisible()
}

test('gestiona torneos y participaciones offline, conserva identidades y permite acceso desde la plantilla', async ({ page, context }) => {
  const external: string[] = []
  const errors: string[] = []
  context.on('request', (request) => {
    if (/^https?:/.test(request.url()) && new URL(request.url()).hostname !== '127.0.0.1') external.push(request.url())
  })
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width: 1024, height: 768 })
  await configured(page)
  await page.evaluate(async () => {
    await navigator.serviceWorker.ready
    if (!navigator.serviceWorker.controller) await new Promise<void>((resolve) => navigator.serviceWorker.addEventListener('controllerchange', () => resolve(), { once: true }))
  })
  await context.setOffline(true)
  await page.getByRole('button', { name: 'Nuevo torneo', exact: true }).click()
  const form = page.getByRole('form', { name: 'Nuevo torneo', exact: true })
  await form.getByRole('button', { name: 'Guardar torneo', exact: true }).click()
  await expect(form.getByRole('alert')).toContainText('Revisa los datos')
  await form.getByLabel('Nombre del torneo', { exact: true }).fill('Copa Sur')
  await form.getByLabel('Temporada del torneo', { exact: true }).selectOption({ label: '2026' })
  await expect(form.getByRole('checkbox', { name: /Equipo otra temporada/ })).toHaveCount(0)
  await form.getByRole('checkbox', { name: 'Iruka Sub 16 · Femenino · Sub 16', exact: true }).check()
  await form.getByRole('checkbox', { name: 'Iruka Sub 14 · Femenino · Sub 14', exact: true }).check()
  await form.getByLabel('Tipo de competición', { exact: true }).fill('Copa')
  await form.getByLabel('Notas del torneo (opcional)').fill('Cancha principal\nJornada de apertura')
  await form.getByRole('button', { name: 'Guardar torneo', exact: true }).click({ clickCount: 2 })
  const table = page.getByRole('table', { name: 'Torneos del club' })
  const copa = table.getByRole('row').filter({ has: page.getByRole('rowheader', { name: /Copa Sur/ }) })
  await expect(copa).toHaveCount(1)
  await expect(copa.getByRole('link')).toHaveCount(2)
  await createTournament(page, 'Liga Regional')

  await page.getByRole('button', { name: 'Editar torneo Copa Sur', exact: true }).click()
  const edit = page.getByRole('form', { name: 'Editar torneo', exact: true })
  await expect(edit.getByLabel('Temporada del torneo', { exact: true })).toBeDisabled()
  await edit.getByRole('checkbox', { name: 'Iruka Sub 14 · Femenino · Sub 14', exact: true }).uncheck()
  await edit.getByRole('button', { name: 'Guardar torneo', exact: true }).click()
  await expect(copa.getByRole('link')).toHaveCount(1)
  await page.getByRole('button', { name: 'Editar torneo Copa Sur', exact: true }).click()
  await edit.getByRole('checkbox', { name: 'Iruka Sub 14 · Femenino · Sub 14', exact: true }).check()
  await edit.getByRole('button', { name: 'Guardar torneo', exact: true }).click()
  await expect(copa.getByRole('link')).toHaveCount(2)
  await page.getByRole('button', { name: 'Archivar torneo Copa Sur', exact: true }).click()
  await expect(page.getByRole('rowheader', { name: /Copa Sur/ })).toHaveCount(0)
  await page.getByRole('checkbox', { name: 'Ver solo torneos archivados' }).check()
  await page.getByRole('button', { name: 'Restaurar torneo Copa Sur', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Ver solo torneos archivados' }).uncheck()
  await expect(copa.getByRole('link')).toHaveCount(2)
  await copa.getByRole('link', { name: 'Iruka Sub 14 · Femenino · Sub 14', exact: true }).click()
  await page.getByRole('link', { name: 'Ver torneos de esta plantilla', exact: true }).click()
  await expect(page.getByRole('rowheader', { name: /Copa Sur/ })).toBeVisible()
  await expect(page.getByRole('rowheader', { name: /Liga Regional/ })).toHaveCount(0)
  await page.getByLabel('Filtrar torneos por equipo y temporada', { exact: true }).selectOption('')
  await expect(page.getByRole('rowheader', { name: /Liga Regional/ })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('rowheader', { name: /Copa Sur/ })).toBeVisible()
  await page.screenshot({ path: 'test-results/torneos-offline.png', fullPage: true })

  const reopened = await context.newPage()
  await reopened.goto('/#/torneos')
  await expect(reopened.getByRole('rowheader', { name: /Copa Sur/ })).toBeVisible()
  await reopened.setViewportSize({ width: 375, height: 812 })
  await reopened.getByRole('button', { name: 'Editar torneo Copa Sur', exact: true }).click()
  await expect(reopened.getByLabel('Notas del torneo (opcional)')).toHaveValue('Cancha principal\nJornada de apertura')
  const save = reopened.getByRole('button', { name: 'Guardar torneo', exact: true })
  expect((await save.boundingBox())?.height).toBeGreaterThanOrEqual(44)
  expect(await reopened.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await expect(reopened.getByRole('rowheader', { name: /Copa Sur/ })).toBeVisible()
  await reopened.screenshot({ path: 'test-results/torneo-movil.png', fullPage: true })
  expect(external).toEqual([])
  expect(errors).toEqual([])
})

test('protege el torneo ante ediciones concurrentes y conserva el formulario ante duplicados', async ({ page, context }) => {
  await configured(page)
  await createTournament(page, 'Copa Sur')
  const second = await context.newPage()
  await second.goto('/#/torneos')
  await second.getByRole('button', { name: 'Editar torneo Copa Sur', exact: true }).click()
  await page.getByRole('button', { name: 'Editar torneo Copa Sur', exact: true }).click()
  await page.getByLabel('Nombre del torneo', { exact: true }).fill('Copa confirmada')
  await page.getByRole('button', { name: 'Guardar torneo', exact: true }).click()
  await expect(page.getByRole('rowheader', { name: /Copa confirmada/ })).toBeVisible()
  await second.getByLabel('Nombre del torneo', { exact: true }).fill('Edición antigua')
  await second.getByRole('button', { name: 'Guardar torneo', exact: true }).click()
  await expect(second.getByRole('alert')).toContainText('otra edición')
  await expect(second.getByLabel('Nombre del torneo', { exact: true })).toHaveValue('Edición antigua')
  await second.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await second.getByRole('button', { name: 'Nuevo torneo', exact: true }).click()
  await second.getByLabel('Nombre del torneo', { exact: true }).fill('COPA CONFIRMADA')
  await second.getByLabel('Temporada del torneo', { exact: true }).selectOption({ label: '2026' })
  await second.getByRole('checkbox', { name: 'Iruka Sub 16 · Femenino · Sub 16', exact: true }).check()
  await second.getByRole('button', { name: 'Guardar torneo', exact: true }).click()
  await expect(second.getByRole('alert')).toContainText('Ya existe un torneo')
  await expect(second.getByLabel('Nombre del torneo', { exact: true })).toHaveValue('COPA CONFIRMADA')
  await second.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await page.getByRole('navigation').getByRole('link', { name: 'Temporadas', exact: true }).click()
  await page.getByRole('button', { name: 'Archivar temporada 2026', exact: true }).click()
  const row = second.getByRole('row').filter({ has: second.getByRole('rowheader', { name: /Copa confirmada/ }) })
  await expect(row.getByText('Temporada archivada', { exact: true })).toBeVisible()
  await expect(second.getByRole('button', { name: 'Editar torneo Copa confirmada', exact: true })).toBeDisabled()
  await second.getByRole('button', { name: 'Archivar torneo Copa confirmada', exact: true }).click()
  await second.getByRole('checkbox', { name: 'Ver solo torneos archivados' }).check()
  await expect(second.getByRole('button', { name: 'Restaurar torneo Copa confirmada', exact: true })).toBeDisabled()
})
