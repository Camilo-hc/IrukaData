import { expect, test, type Page } from '@playwright/test'

async function configureClub(page: Page) {
  await page.goto('/#/deportistas')
  await page.getByLabel('Nombre del club', { exact: true }).fill('Club de prueba')
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Nuevo deportista', exact: true })).toBeVisible()
}
async function prepareOffline(page: Page) {
  await page.evaluate(async () => {
    await navigator.serviceWorker.ready
    if (!navigator.serviceWorker.controller) {
      await new Promise<void>((resolve) => navigator.serviceWorker.addEventListener('controllerchange', () => resolve(), { once: true }))
    }
  })
}
async function createSimpleProfile(page: Page, name: string) {
  await page.getByRole('button', { name: 'Nuevo deportista', exact: true }).click()
  await page.getByLabel('Nombre del deportista', { exact: true }).fill(name)
  await page.getByRole('button', { name: 'Guardar', exact: true }).click({ clickCount: 2 })
  await page.getByRole('table', { name: 'Deportistas del club' }).getByRole('link', { name, exact: true }).click()
  await expect(page.getByRole('heading', { level: 1, name, exact: true })).toBeVisible()
}

test('gestiona perfiles y homónimos offline, conserva IDs y permite vaciar datos opcionales', async ({ page, context }) => {
  const external: string[] = []
  const errors: string[] = []
  context.on('request', (request) => {
    if (/^https?:/.test(request.url()) && new URL(request.url()).hostname !== '127.0.0.1') external.push(request.url())
  })
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width: 1024, height: 768 })
  await configureClub(page)
  await prepareOffline(page)
  await context.setOffline(true)
  await page.getByRole('button', { name: 'Nuevo deportista', exact: true }).click()
  let form = page.getByRole('form', { name: 'Nuevo deportista', exact: true })
  await form.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(form.getByText('Escribe un nombre.', { exact: true })).toBeVisible()
  await form.getByLabel('Nombre del deportista', { exact: true }).fill('María Ríos')
  await form.getByLabel('Fecha de nacimiento (opcional)', { exact: true }).fill('9999-12-31')
  await form.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(form.getByText('La fecha de nacimiento no puede ser futura.', { exact: true })).toBeVisible()
  await form.getByLabel('Fecha de nacimiento (opcional)', { exact: true }).fill('2008-02-29')
  await form.getByLabel('Notas (opcional)', { exact: true }).fill('Primera línea de prueba.\nSegunda línea de prueba.')
  await form.getByRole('button', { name: 'Guardar', exact: true }).click({ clickCount: 2 })
  await expect(page.getByRole('table', { name: 'Deportistas del club' }).getByRole('row')).toHaveCount(2)
  await page.getByLabel('Buscar deportista por nombre').fill('MARIA RIOS')
  await expect(page.getByRole('link', { name: 'María Ríos', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'María Ríos', exact: true }).click()
  await expect(page.getByRole('article', { name: 'Ficha del deportista' }).getByText('29-02-2008', { exact: true })).toBeVisible()
  await expect(page.locator('.athlete-notes')).toHaveText('Primera línea de prueba.\nSegunda línea de prueba.')
  const originalUrl = page.url()
  await page.reload()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('María Ríos')
  await page.getByRole('button', { name: 'Editar perfil', exact: true }).click()
  form = page.getByRole('form', { name: 'Editar deportista', exact: true })
  await expect(form.getByLabel('Fecha de nacimiento (opcional)', { exact: true })).toHaveValue('2008-02-29')
  await form.getByLabel('Nombre del deportista', { exact: true }).fill('María Ríos Actualizada')
  await form.getByLabel('Fecha de nacimiento (opcional)', { exact: true }).fill('')
  await form.getByLabel('Notas (opcional)', { exact: true }).fill('')
  await form.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('María Ríos Actualizada')
  await expect(page).toHaveURL(originalUrl)
  await expect(page.getByText('No registrada', { exact: true })).toBeVisible()
  await expect(page.getByText('Sin notas.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Archivar deportista', exact: true }).click()
  await expect(page.getByText('Archivado', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Editar perfil', exact: true })).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Restaurar deportista', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Volver a deportistas', exact: true }).click()
  await expect(page.getByRole('link', { name: 'María Ríos Actualizada', exact: true })).toHaveCount(0)
  await page.getByRole('checkbox', { name: 'Ver solo deportistas archivados' }).check()
  await page.getByRole('button', { name: 'Restaurar deportista María Ríos Actualizada', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Ver solo deportistas archivados' }).uncheck()
  await page.getByRole('link', { name: 'María Ríos Actualizada', exact: true }).click()
  await expect(page).toHaveURL(originalUrl)
  await page.screenshot({ path: 'test-results/deportista-offline.png', fullPage: true })
  await page.getByRole('link', { name: 'Volver a deportistas', exact: true }).click()
  await page.getByRole('button', { name: 'Nuevo deportista', exact: true }).click()
  form = page.getByRole('form', { name: 'Nuevo deportista', exact: true })
  await form.getByLabel('Nombre del deportista', { exact: true }).fill('María Ríos Actualizada')
  await expect(form.getByRole('complementary', { name: 'Perfiles con el mismo nombre' })).toBeVisible()
  await form.getByLabel('Fecha de nacimiento (opcional)', { exact: true }).fill('2009-01-01')
  await form.getByRole('button', { name: 'Guardar', exact: true }).click()
  const table = page.getByRole('table', { name: 'Deportistas del club' })
  await expect(table.getByRole('row')).toHaveCount(3)
  const homonymRow = table.getByRole('row').filter({ has: page.getByRole('cell', { name: '01-01-2009', exact: true }) })
  await homonymRow.getByRole('link', { name: 'María Ríos Actualizada', exact: true }).click()
  expect(page.url()).not.toBe(originalUrl)
  await page.getByRole('link', { name: 'Volver a deportistas', exact: true }).click()
  await page.screenshot({ path: 'test-results/deportistas-offline.png', fullPage: true })
  const reopened = await context.newPage()
  reopened.on('pageerror', (error) => errors.push(error.message))
  await reopened.goto(originalUrl)
  await expect(reopened.getByRole('heading', { level: 1 })).toHaveText('María Ríos Actualizada')
  await expect(reopened.getByText('No registrada', { exact: true })).toBeVisible()
  expect(external).toEqual([])
  expect(errors).toEqual([])
})

test('rechaza la edición antigua de un perfil abierto en dos pestañas', async ({ page, context }) => {
  await configureClub(page)
  await createSimpleProfile(page, 'Álex Marín')
  const profileUrl = page.url()
  const second = await context.newPage()
  await second.goto(profileUrl)
  await second.getByRole('button', { name: 'Editar perfil', exact: true }).click()
  await page.getByRole('button', { name: 'Editar perfil', exact: true }).click()
  await page.getByLabel('Notas (opcional)', { exact: true }).fill('Nota confirmada')
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.locator('.athlete-notes')).toHaveText('Nota confirmada')
  await second.getByLabel('Notas (opcional)', { exact: true }).fill('Nota de una edición antigua')
  await second.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(second.getByRole('alert')).toContainText('otra edición')
  await expect(second.getByLabel('Notas (opcional)', { exact: true })).toHaveValue('Nota de una edición antigua')
  await second.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await expect(second.locator('.athlete-notes')).toHaveText('Nota confirmada')
  await expect(second).toHaveURL(profileUrl)
})

